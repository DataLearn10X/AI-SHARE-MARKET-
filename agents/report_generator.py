"""AI research report generator (Day 15)."""

from __future__ import annotations

import logging
from datetime import datetime
from pathlib import Path
from typing import Tuple

from agents.research_agent import gather_context, build_context_text
from config.settings import PROJECT_ROOT
from services.llm_service import generate_text

logger = logging.getLogger(__name__)

REPORTS_DIR = PROJECT_ROOT / "reports"


def _save_report(symbol: str, content: str) -> Path:
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    path = REPORTS_DIR / f"{symbol}_{ts}.md"
    path.write_text(content, encoding="utf-8")
    return path


def generate_report(symbol: str) -> Tuple[str, Path]:
    """Generate a structured research report and save it to disk.

    Returns (markdown_content, file_path).
    """
    symbol = symbol.strip().upper()
    data = gather_context(symbol)
    context = data["context_text"]
    profile = data.get("profile", {})
    ratios = data.get("latest_ratios", {})
    val = data.get("valuation", {})
    score = data.get("score", {})

    system = (
        "You are a financial research analyst. Write a structured research report using ONLY the provided verified data. "
        "Sections: 1) Company Overview 2) Financial Performance 3) Profitability & Returns 4) Leverage & Liquidity "
        "5) Valuation 6) Fundamental Score 7) Risks & Caveats 8) Conclusion. "
        "Cite the reporting period for every figure. Do not invent numbers. "
        "This is research, not investment advice."
    )
    prompt = f"Context:\n{context}\n\nGenerate a detailed research report for {symbol}."
    llm_report = generate_text(prompt, system=system)

    if llm_report:
        content = llm_report.strip()
        content += "\n\n---\n*Generated by AI Share Market Research Agent. Data sourced from yfinance (unofficial) + local company master (sample seed). Not investment advice.*"
    else:
        content = _fallback_report(data)

    path = _save_report(symbol, content)
    return content, path


